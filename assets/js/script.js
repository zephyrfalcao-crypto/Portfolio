let currentLanguage = localStorage.getItem("portfolio-language") || "fr";

const applyLanguage = (language) => {
    currentLanguage = language;
    document.documentElement.lang = language;
    const dict = translations[language];

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;
        if (dict[key] !== undefined) element.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        if (dict[key] !== undefined) element.placeholder = dict[key];
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
        const key = element.dataset.i18nAria;
        if (dict[key] !== undefined) element.setAttribute("aria-label", dict[key]);
    });

    document.querySelectorAll("[data-stepper-prev] [data-i18n]").forEach((element) => element.textContent = dict[element.dataset.i18n]);
    document.querySelectorAll("[data-stepper-next] [data-i18n]").forEach((element) => element.textContent = dict[element.dataset.i18n]);

    const toggle = document.getElementById("language-toggle");
    if (toggle) {
        toggle.querySelector("span:first-child").textContent = language === "fr" ? "FR" : "EN";
        toggle.querySelector(".language-toggle-current").textContent = language === "fr" ? "EN" : "FR";
        toggle.setAttribute("aria-label", language === "fr" ? "Passer en anglais" : "Switch to French");
    }

    document.title = language === "fr" ? "Portfolio — Andry Fitiavana" : "Portfolio — Andry Fitiavana";
    localStorage.setItem("portfolio-language", language);
};

const languageToggle = document.getElementById("language-toggle");
if (languageToggle) {
    languageToggle.addEventListener("click", () => {
        applyLanguage(currentLanguage === "fr" ? "en" : "fr");
    });
}

applyLanguage(currentLanguage);

// Menu mobile
const menuBtn = document.getElementById("menu-btn");
const navLinks = document.querySelector(".nav-links");

if (menuBtn && navLinks) {
    menuBtn.addEventListener("click", () => {
        const isOpen = navLinks.classList.toggle("open");
        menuBtn.setAttribute("aria-expanded", isOpen ? "true" : "false");
        menuBtn.setAttribute("aria-label", isOpen ? translations[currentLanguage]["menu.close"] : translations[currentLanguage]["menu.open"]);
        menuBtn.textContent = isOpen ? "×" : "=";
    });

    navLinks.querySelectorAll("a").forEach((link) => {
        link.addEventListener("click", () => {
            navLinks.classList.remove("open");
            menuBtn.setAttribute("aria-expanded", "false");
            menuBtn.setAttribute("aria-label", translations[currentLanguage]["menu.open"]);
            menuBtn.textContent = "=";
        });
    });
}

// Navigation active au défilement
const header = document.querySelector(".header");
const sections = document.querySelectorAll("main section[id]");
const navItems = document.querySelectorAll(".nav-links a[href^='#']");

const updateHeaderState = () => {
    if (!header) return;
    header.classList.toggle("scrolled", window.scrollY > 24);
};

if (sections.length && navItems.length) {
    const setActiveLink = () => {
        let currentId = "";

        sections.forEach((section) => {
            const sectionTop = section.offsetTop - 140;
            const sectionBottom = sectionTop + section.offsetHeight;
            if (window.scrollY >= sectionTop && window.scrollY < sectionBottom) {
                currentId = section.id;
            }
        });

        if (!currentId && window.scrollY < 200) {
            currentId = "accueil";
        }

        navItems.forEach((link) => {
            const isActive = link.getAttribute("href") === `#${currentId}`;
            link.classList.toggle("active", isActive);
        });
    };

    const handleScroll = () => {
        updateHeaderState();
        setActiveLink();
    };

    window.addEventListener("scroll", handleScroll, { passive: true });
    window.addEventListener("load", handleScroll);
    handleScroll();
} else {
    window.addEventListener("scroll", updateHeaderState, { passive: true });
    window.addEventListener("load", updateHeaderState);
    updateHeaderState();
}

const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

// Navigation pas à pas des compétences et des projets
document.querySelectorAll("[data-stepper]").forEach((stepper) => {
    const items = Array.from(stepper.querySelectorAll("[data-stepper-item]"));
    const controls = stepper.parentElement.querySelector("[data-stepper-controls]");

    if (items.length < 2 || !controls) return;

    const previousButton = controls.querySelector("[data-stepper-prev]");
    const nextButton = controls.querySelector("[data-stepper-next]");
    const count = controls.querySelector("[data-stepper-count]");
    const progress = controls.querySelector("[data-stepper-progress]");
    let activeIndex = 0;

    const showItem = (nextIndex) => {
        activeIndex = nextIndex;

        items.forEach((item, index) => {
            const isActive = index === activeIndex;
            item.hidden = !isActive;
            item.classList.remove("stepper-enter");

            if (isActive && !prefersReducedMotion) {
                void item.offsetWidth;
                item.classList.add("stepper-enter");
            }
        });

        previousButton.disabled = activeIndex === 0;
        nextButton.disabled = activeIndex === items.length - 1;
        count.textContent = `${String(activeIndex + 1).padStart(2, "0")} / ${String(items.length).padStart(2, "0")}`;
        progress.style.width = `${((activeIndex + 1) / items.length) * 100}%`;
    };

    previousButton.addEventListener("click", () => {
        if (activeIndex > 0) showItem(activeIndex - 1);
    });
    nextButton.addEventListener("click", () => {
        if (activeIndex < items.length - 1) showItem(activeIndex + 1);
    });

    controls.hidden = false;
    showItem(0);
});

